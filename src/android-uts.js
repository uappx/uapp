import fs from 'fs-extra'
import path from 'node:path'

const begin = '// BEGIN UAPP UTS'
const end = '// END UAPP UTS'
const block = /\/\/ BEGIN UAPP UTS\r?\n[\s\S]*?\/\/ END UAPP UTS\r?\n?/g
const quote = value => `'${String(value).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`

function updateBlock(file, body, fallback = '') {
  const original = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : fallback
  const newline = original.includes('\r\n') ? '\r\n' : '\n'
  const content = original.replace(block, '').trimEnd()
  fs.outputFileSync(file, content + (body ? `\n\n${begin}\n${body}\n${end}`.replace(/\n/g, newline) : '') + newline)
}

function filesIn(directory) {
  if (!fs.existsSync(directory)) return []
  return fs.readdirSync(directory, { withFileTypes: true }).flatMap(entry => {
    const file = path.join(directory, entry.name)
    return entry.isDirectory() ? filesIn(file) : [file]
  })
}

export function syncAndroidPlugins(plugins, appDir) {
  const settings = path.join(appDir, 'settings.gradle')
  const appBuild = path.join(appDir, 'app/build.gradle')
  if (fs.existsSync(path.join(appDir, 'settings.gradle.kts')) || fs.existsSync(path.join(appDir, 'app/build.gradle.kts'))) {
    throw new Error('UTS 自动接入目前支持官方示例的 Groovy build.gradle，请先转换 Kotlin DSL 配置')
  }

  const pluginsRoot = path.join(appDir, 'UTSPlugins')
  const stateFile = path.join(pluginsRoot, 'uts-android.json')
  const legacyStateFile = path.join(appDir, '.uapp/uts-android.json')
  const previousFile = fs.existsSync(stateFile) ? stateFile : legacyStateFile
  const previous = fs.existsSync(previousFile) ? fs.readJsonSync(previousFile) : {}
  const migrations = Object.keys(previous).map(id => {
    if (!/^[A-Za-z][\w-]*$/.test(id)) throw new Error('无效的 UTS 同步记录')
    return [path.join(appDir, id), path.join(pluginsRoot, id)]
  }).filter(([source]) => fs.existsSync(source))

  for (const [source, target] of migrations) {
    if (fs.existsSync(target)) throw new Error(`UTS 迁移目标已存在：${target}`)
  }
  for (const [source, target] of migrations) fs.moveSync(source, target)

  const state = {}
  const rootBuild = fs.existsSync(path.join(appDir, 'build.gradle')) ? fs.readFileSync(path.join(appDir, 'build.gradle'), 'utf8') : ''
  const kotlinInRoot = /org\.jetbrains\.kotlin\.android/.test(rootBuild)
  const builtInKotlin = Number(rootBuild.match(/id\s*['"]com\.android\.(?:application|library)['"]\s+version\s*['"](\d+)/)?.[1]) >= 9
  const plans = [...plugins].map(([id, source]) => {
    if (!/^[A-Za-z][\w-]*$/.test(id) || ['app', 'build', 'gradle'].includes(id)) throw new Error(`不支持的 UTS 模块名：${id}`)
    const configFile = path.join(source, 'config.json')
    const config = fs.existsSync(configFile) ? fs.readJsonSync(configFile) : {}
    const manifestFile = path.join(source, 'AndroidManifest.xml')
    const manifest = fs.existsSync(manifestFile) ? fs.readFileSync(manifestFile, 'utf8') : '<manifest />\n'
    const namespace = manifest.match(/\bpackage\s*=\s*["']([^"']+)["']/)?.[1] || `uts.sdk.modules.${id.replace(/-([a-zA-Z])/g, (_, c) => c.toUpperCase())}`
    const copies = []

    for (const [from, to] of [['src', 'src/main/java'], ['assets', 'src/main/assets'], ['res', 'src/main/res'], ['libs', 'libs']]) {
      for (const file of filesIn(path.join(source, from))) copies.push([file, path.join(to, path.relative(path.join(source, from), file))])
    }

    const owned = [...copies.map(([, target]) => target), 'src/main/AndroidManifest.xml', 'uapp-uts.gradle']
    const moduleDir = path.join(pluginsRoot, id)

    for (const target of owned) {
      if (fs.existsSync(path.join(moduleDir, target)) && !previous[id]?.includes(target)) {
        throw new Error(`UTS 目标已有手工文件，未覆盖：${id}/${target}`)
      }
    }

    return { id, source, config, manifest, namespace, copies, owned, moduleDir }
  })

  for (const [id, owned] of Object.entries(previous)) {
    if (!/^[A-Za-z][\w-]*$/.test(id)) throw new Error('无效的 UTS 同步记录')
    for (const file of owned) {
      if (path.isAbsolute(file) || file.split(/[\\/]/).includes('..')) throw new Error('无效的 UTS 同步路径')
      fs.removeSync(path.join(pluginsRoot, id, file))
    }
    if (!plugins.has(id)) updateBlock(path.join(pluginsRoot, id, 'build.gradle'), '')
  }

  for (const plan of plans) {
    const { id, config, manifest, namespace, copies, owned, moduleDir } = plan
    for (const [source, target] of copies) fs.copySync(source, path.join(moduleDir, target))
    fs.outputFileSync(path.join(moduleDir, 'src/main/AndroidManifest.xml'), manifest.replace(/\s+package\s*=\s*(["'])[^"']*\1/, ''))
    const dependencies = (config.dependencies || []).map(dep => typeof dep === 'string' ? `implementation ${quote(dep)}` : dep.source)
    const generated = `// Generated by uapp prepare; customize build.gradle instead.
evaluationDependsOn(':app')
def host = project(':app').android
android {
    if (!namespace) namespace = ${quote(namespace)}
    compileSdk = host.compileSdk
    defaultConfig {
        minSdk = Math.max(host.defaultConfig.minSdk ?: 21, ${Number(config.minSdkVersion || 21)})
        ${config.abis?.length ? `ndk { abiFilters ${config.abis.map(quote).join(', ')} }` : ''}
    }
    compileOptions {
        sourceCompatibility = host.compileOptions.sourceCompatibility
        targetCompatibility = host.compileOptions.targetCompatibility
    }
}

${builtInKotlin ? '' : `kotlin {
    compilerOptions {
        jvmTarget = org.jetbrains.kotlin.gradle.dsl.JvmTarget.fromTarget(host.compileOptions.targetCompatibility.toString())
    }
}
`}
dependencies {
    compileOnly fileTree(dir: rootProject.file('app/libs'), include: ['*.aar', '*.jar'])
    compileOnly fileTree(dir: file('libs'), include: ['*.aar', '*.jar'])
    compileOnly files(System.properties['user.home'] + '/.uappsdk/android/SDK/libs/utsplugin-release.aar')
    compileOnly 'com.alibaba:fastjson:1.2.83'
    compileOnly 'androidx.core:core-ktx:1.6.0'
    compileOnly 'org.jetbrains.kotlinx:kotlinx-coroutines-core:1.8.1'
    compileOnly 'org.jetbrains.kotlinx:kotlinx-coroutines-android:1.8.1'
    ${dependencies.join('\n    ')}
}
`
    fs.outputFileSync(path.join(moduleDir, 'uapp-uts.gradle'), generated.replace(/^[ \t]+$/gm, ''))
    updateBlock(path.join(moduleDir, 'build.gradle'), "apply from: 'uapp-uts.gradle'", `plugins {\n    id 'com.android.library'\n${builtInKotlin ? '' : `    id 'org.jetbrains.kotlin.android'${kotlinInRoot ? '' : " version '2.2.10'"}\n`}}\n`)
    state[id] = owned
    for (const key of ['project', 'hooksClass', 'components']) {
      if (config[key]) console.warn(`UTS ${id}: 请按官方文档检查 ${key} 的原生配置，自动接入不改写此配置`)
    }
  }

  const settingsText = fs.existsSync(settings) ? fs.readFileSync(settings, 'utf8').replace(block, '') : ''
  const appText = fs.readFileSync(appBuild, 'utf8').replace(block, '')
  const includes = plans.filter(({ id }) => !settingsText.includes(`':${id}'`) && !settingsText.includes(`":${id}"`))
  const refs = plans.filter(({ id }) => !appText.includes(`project(':${id}')`) && !appText.includes(`project(":${id}")`))
  updateBlock(settings, [...includes.map(({ id }) => `include ':${id}'`), ...plans.map(({ id }) => `project(':${id}').projectDir = file('UTSPlugins/${id}')`)].join('\n'), "include ':app'\n")

  const deps = refs.map(({ id }) => `    implementation project(':${id}')`)
  for (const { id } of plans) deps.push(`    implementation fileTree(dir: rootProject.file('UTSPlugins/${id}/libs'), include: ['*.aar', '*.jar'])`)
  const minSdk = Math.max(21, ...plans.map(({ config }) => Number(config.minSdkVersion || 21)))
  updateBlock(appBuild, deps.length ? `dependencies {\n${deps.join('\n')}\n}\nandroid.defaultConfig {\n    minSdk = Math.max(minSdk ?: 21, ${minSdk})\n}` : '')
  fs.outputJsonSync(stateFile, state, { spaces: 2 })
  fs.removeSync(legacyStateFile)
}
